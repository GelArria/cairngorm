// Writes licenses/THIRD-PARTY-NOTICES.txt: the license texts of every Rust crate the app
// compiles and every production npm package (app frontend and agent sidecar), grouped by
// identical text. Reads the committed lockfiles (git HEAD) so local, uncommitted dependency
// experiments never reach a release; license files come from the installed packages.
// `--check` fails when the checked-in file is out of date.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { compiledCrates } from "./lib/compiled-crates.mjs";

const root = resolve(import.meta.dirname, "..");
const output = join(root, "licenses/THIRD-PARTY-NOTICES.txt");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright)([-._].*)?$/i;

const git = (...args) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 << 20 });

function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) {
    return "";
  }
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").replace(/\r\n?/g, "\n").trim())
    .filter(Boolean)
    .join("\n\n");
}

/** Production packages from a committed npm lockfile, with their installed folder. */
function npmPackages(lockPath) {
  const lock = JSON.parse(git("show", `HEAD:${lockPath}`));
  const base = join(root, dirname(lockPath));
  return Object.entries(lock.packages ?? {})
    .filter(([path, info]) => path && !info.dev && !info.devOptional && !info.link)
    .map(([path, info]) => ({
      name: info.name ?? path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: info.version,
      license: info.license ?? "UNKNOWN",
      source: "npm",
      dir: join(base, path),
    }));
}

/** Every crate the app compiles, for all platforms. */
function cratePackages() {
  return compiledCrates(root).map((pkg) => ({
    name: pkg.name,
    version: pkg.version,
    license: pkg.license ?? (pkg.license_file ? "see license file" : "UNKNOWN"),
    source: "crates.io",
    dir: dirname(pkg.manifest_path),
  }));
}

function render() {
  const packages = [
    ...cratePackages(),
    ...npmPackages("package-lock.json"),
    ...npmPackages("src/agent/core/package-lock.json"),
  ];
  const unique = new Map();
  for (const pkg of packages) {
    unique.set(`${pkg.source}:${pkg.name}@${pkg.version}`, pkg);
  }
  const groups = new Map();
  const withoutText = [];
  for (const pkg of unique.values()) {
    const text = licenseTexts(pkg.dir);
    const label = `${pkg.name} ${pkg.version} (${pkg.source}, ${pkg.license})`;
    if (text) {
      groups.set(text, [...(groups.get(text) ?? []), label]);
    } else {
      withoutText.push(label);
    }
  }
  const rule = "=".repeat(80);
  const sections = [...groups.entries()]
    .map(([text, labels]) => [labels.sort(), text])
    .sort(([a], [b]) => a[0].localeCompare(b[0]))
    .map(
      ([labels, text]) =>
        `${rule}\nApplies to:\n  ${labels.join("\n  ")}\n${"-".repeat(80)}\n${text}\n`,
    );
  return [
    "Third-party notices for Cairngorm",
    "",
    "Cairngorm is released under the MIT License (see LICENSE). It includes the open-source",
    "components below, each under its own license. Every section gives a license text as the",
    "component ships it and the components it covers. Bundled fonts and other assets have",
    "their own notices in the licenses/ folder and beside those assets.",
    "",
    `Generated by scripts/third-party-notices.mjs: ${unique.size} components.`,
    "",
    ...sections,
    rule,
    "Components that ship no license file (their declared license applies):",
    ...withoutText.sort().map((label) => `  ${label}`),
    "",
  ].join("\n");
}

const notices = render();
if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== notices) {
    console.error(
      "licenses/THIRD-PARTY-NOTICES.txt is out of date: run node scripts/third-party-notices.mjs",
    );
    process.exit(1);
  }
  console.log("Third-party notices are current");
} else {
  writeFileSync(output, notices);
  console.log(`Wrote ${output} (${(notices.length / 1024).toFixed(0)} KB)`);
}
